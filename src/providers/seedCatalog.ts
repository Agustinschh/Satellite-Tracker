/**
 * Embedded reference OMM/TLE catalog so the application can operate offline
 * immediately and gracefully survive total network outages.
 * When online, CelesTrak / Space-Track / WhereTheISS replace these with live ephemerides.
 */
function buildEpochRecentIso(hoursAgo = 4): string {
  const d = new Date(Date.now() - hoursAgo * 3600 * 1000);
  return d.toISOString();
}

